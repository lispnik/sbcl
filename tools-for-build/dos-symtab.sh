#!/bin/sh
# Generate the C runtime's table of foreign symbols for the DOS port.
#
# DOS has no dlsym(), so the runtime carries a table of every symbol Lisp
# may look up by name:
#   - all public symbols of the runtime's own object files, taken from the
#     linker map of a preliminary link (the equivalent of linking with
#     --export-dynamic elsewhere);
#   - C library functions, redirected to the dosw_* wrappers in dos-wrap.c
#     and dos-sock.c (the library's own entry points are not callable
#     from Lisp);
#   - anything listed in dos-extra-syms.txt.
# Every name genesis recorded for the cold core (section IX of
# cold-sbcl.map) must be resolvable, or the script fails.
#
# usage: dos-symtab.sh linker.map cold-sbcl.map dos-extra-syms.txt dos-wrap.c... > dos-symtab.c
set -e
linkmap=$1; coldmap=$2; extra=$3; shift 3
tmp=${TMPDIR:-/tmp}/dos-symtab.$$
trap 'rm -f $tmp.*' 0

# name<TAB>C-symbol pairs
{
    # public symbols of our own modules ("_name" under cdecl naming)
    awk '/^Module: /{ours = ($2 ~ /^dos-obj\//) && ($2 !~ /dos-symtab/); next}
         ours && $2 ~ /^_[A-Za-z][A-Za-z0-9_]*$/ {n = substr($2, 2); if (n !~ /^dosw_/) print n "\t" n}' "$linkmap"
    # wrapped C library functions: dosw_NAME(...) and the M1()/M2() math wrappers
    { cat "$@" | sed -n 's/^[A-Za-z_][A-Za-z0-9_ *]*[ *]dosw_\([A-Za-z0-9_]*\)(.*/\1/p'
      cat "$@" | grep -v '^#define' | grep -o 'M[12]([a-z0-9]*)' | sed 's/M[12](\(.*\))/\1/'
    } | awk '{print $1 "\tdosw_" $1}'
    sed -e 's/#.*//' -e '/^[ 	]*$/d' "$extra" | awk '{print $1 "\t" $1}'
} | LC_ALL=C sort -u -k1,1 > $tmp.syms

# everything the cold core needs must be there
awk '/^IX\. /{on=1; next} /^[XVI]+\. /{on=0} on && / = /{print $NF}' "$coldmap" | LC_ALL=C sort -u > $tmp.cold
cut -f1 $tmp.syms > $tmp.names
missing=`LC_ALL=C comm -23 $tmp.cold $tmp.names`
if [ -n "$missing" ]; then
    echo "dos-symtab.sh: the cold core refers to symbols the runtime does not define:" >&2
    echo "$missing" >&2
    exit 1
fi

echo "/* Generated by tools-for-build/dos-symtab.sh -- do not edit. */"
echo "struct dos_symbol { const char *name; void *address; };"
cut -f2 $tmp.syms | LC_ALL=C sort -u | sed 's/.*/extern char &;/'
echo "const struct dos_symbol dos_symtab[] = {    /* sorted by name */"
awk -F'\t' '{printf "    { \"%s\", &%s },\n", $1, $2}' $tmp.syms
echo "};"
echo "const int dos_symtab_size = sizeof dos_symtab / sizeof dos_symtab[0];"
